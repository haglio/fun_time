from __future__ import annotations

import threading
from typing import Any

from .chrome_tab_node import UiaNode
from .chrome_tabs import AccessibleNode

_this_thread = threading.local()


def open_chrome_window(hwnd: int) -> AccessibleNode:
    automation = getattr(_this_thread, "automation", None)
    if automation is None:
        automation = _this_thread.automation = _Automation()
    return automation.window(hwnd)


class _Automation:
    def __init__(self) -> None:
        import comtypes  # noqa: PLC0415  (COM starts on whichever thread imports it)
        import comtypes.client  # noqa: PLC0415

        comtypes.CoInitialize()
        comtypes.client.GetModule("UIAutomationCore.dll")
        from comtypes.gen import UIAutomationClient  # noqa: PLC0415  (generated by the line above)

        self.uia: Any = UIAutomationClient
        self.client: Any = comtypes.client.CreateObject(
            UIAutomationClient.CUIAutomation, interface=UIAutomationClient.IUIAutomation)
        self.read_with_each_node: Any = self.client.CreateCacheRequest()
        self.read_with_each_node.AddProperty(UIAutomationClient.UIA_ControlTypePropertyId)
        self.read_with_each_node.AddProperty(UIAutomationClient.UIA_ClassNamePropertyId)
        # Not FindAll, which switched on Chrome 154's accessibility for every open page.
        self.walker: Any = self.client.RawViewWalker

    def window(self, hwnd: int) -> UiaNode:
        return UiaNode.of(self, self.client.ElementFromHandleBuildCache(hwnd, self.read_with_each_node))
